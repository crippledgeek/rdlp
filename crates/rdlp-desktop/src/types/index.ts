// ========== Event Payloads (camelCase — Rust uses #[serde(rename_all = "camelCase")]) ==========

/** Download progress payload emitted as "download-progress". */
export interface DownloadProgressPayload {
    jobId: string;
    progress: number;
    speed: string | null;
    eta: string | null;
    downloadedBytes: number;
    totalBytes: number | null;
    /** True when totalBytes is an extrapolated estimate (segmented download).
     *  Rendered as a `~`-prefixed total size in the desktop progress UI. */
    isEstimated: boolean;
    /** Fragments completed so far (segmented HLS/DASH); null for progressive HTTP.
     *  u64 on the wire; JS `number` is safe for fragment counts (always well
     *  under Number.MAX_SAFE_INTEGER — real streams have thousands, not 2^53). */
    segmentsDownloaded: number | null;
    /** Total fragment count (segmented HLS/DASH); null for progressive HTTP. */
    totalSegments: number | null;
}

/** Download completion payload emitted as "download-complete". */
export interface DownloadCompletePayload {
    jobId: string;
    filepath: string;
}

/** Download error payload emitted as "download-error". */
export interface DownloadErrorPayload {
    jobId: string;
    error: string;
    retryable: boolean;
}

/** Download cancellation payload emitted as "download-cancelled". */
export interface DownloadCancelledPayload {
    jobId: string;
}

/** Log message payload emitted as "download-log". */
export interface DownloadLogPayload {
    jobId: string;
    level: "info" | "warn" | "debug";
    message: string;
}

/** Post-processing progress payload emitted as "postprocess-progress". */
export interface PostProcessProgressPayload {
    jobId: string;
    stage: string;
    progress: number; // 0.0–1.0
    eta: string | null;
}

/** Unit-started payload emitted as "unit-started" (playlist episode or merge stream start). */
export interface UnitStartedPayload {
    jobId: string;
    unitIndex: number;
    unitTotal: number;
    unitTitle: string;
}

