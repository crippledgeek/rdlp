// ========== Download Types ==========

/**
 * Playlist membership context attached to a download job (camelCase — Rust uses #[serde(rename_all = "camelCase")]).
 *
 * Present only when the job is part of a playlist batch download.
 * All fields are required when the object is present.
 */
export interface PlaylistContext {
    playlistId: string;
    playlistTitle: string;
    /** 1-based position of this episode in the playlist. */
    playlistIndex: number;
    /** Total number of episodes in the playlist. */
    playlistCount: number;
}

/** Lifecycle status of a download job (#[serde(rename_all = "lowercase")]). */
export type JobStatus =
    | "pending"
    | "running"
    | "processing"
    | "completed"
    | "failed"
    | "cancelled";

/** Active unit info owned by Rust, serialized under the `currentUnit` wire key. */
export interface CurrentUnit {
    index: number;
    total: number;
    title: string;
}

/** Serializable metadata for a single download job (snake_case — default serde). */
export interface DownloadJob {
    id: string;
    url: string;
    title: string | null;
    status: JobStatus;
    progress: number | null;
    speed: string | null;
    eta: string | null;
    error: string | null;
    retryable: boolean;
    started_at: number | null;
    completed_at: number | null;
    output_path: string | null;
    /** Original options used to start this job (populated by backend). */
    options: DownloadOptions | null;
    /** Playlist membership — null for standalone downloads. Omitted in legacy fixtures. */
    playlist?: PlaylistContext | null;
    /** Current post-processing stage label (e.g. "Merging", "Transcoding"); null outside processing. */
    stage: string | null;
    /** Accumulated log messages from download-log events (frontend-only, not from Rust). */
    logMessages?: string[];
    /** Current unit info, owned by Rust (`currentUnit` wire key). Null when no unit is active. */
    currentUnit: CurrentUnit | null;
    /** Live progress fields merged client-side from `download-progress` events
     *  (camelCase wire keys), not part of the Rust DownloadJob serialization.
     *  Undefined until the first progress event lands for the job. */
    totalBytes?: number | null;
    /** True when `totalBytes` is an extrapolated estimate (segmented download). */
    isEstimated?: boolean;
    /** Fragments completed so far (segmented HLS/DASH); null/undefined otherwise. */
    segmentsDownloaded?: number | null;
    /** Total fragment count (segmented HLS/DASH); null/undefined otherwise. */
    totalSegments?: number | null;
}

